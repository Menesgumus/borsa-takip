# ── Structured output schema ─────────────────────────────────────────────────

class MentorExplanation(BaseModel):
    summary: str = Field(description="A short natural language summary.")
    action_explanation: str = Field(description="Explanation of why this action was chosen.")
    key_reasons: list[str] = Field(description="List of key reason codes or readable reasons.")
    risks: list[str] = Field(description="List of risks associated with this asset/decision.")
    data_quality_note: str | None = Field(default=None, description="Notes on missing or stale data.")
    learning_points: list[str] = Field(description="Educational points explaining the metrics used.")
    action: str = Field(description="Final action (AL, KADEMELI AL, BEKLE, KADEMELI SAT, SAT).")
    synthetic: bool = Field(default=False, description="True if generated by deterministic/mock provider.")


class MentorContext(BaseModel):
    instrument_symbol: str
    current_price: Decimal | None = None
    deterministic_action: DecisionAction
    deterministic_score: Decimal
    reason_codes: list[str]
    missing_data: bool
    news_headlines: list[str] = []


